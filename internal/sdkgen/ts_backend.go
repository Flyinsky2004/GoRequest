// renderTypeScriptFiles renders the complete TypeScript backend file set.
func renderTypeScriptFiles(opts Options, doc *specDoc, ops []Operation, unsupported []UnsupportedOperation, diags []Diagnostic, specDigest string, comp *typeCompiler) ([]File, error) {
	files := []File{
		newFile("types.ts", []byte(renderTSTypes(doc, comp, specDigest)), "source"),
		newFile("errors.ts", []byte(renderTSErrors()), "source"),
		newFile("client.ts", []byte(renderTSClient(opts, doc, specDigest)), "source"),
		newFile("operations.ts", []byte(renderTSOperations(opts, doc, ops, comp, specDigest)), "source"),
		newFile("index.ts", []byte(renderTSIndex()), "source"),
		newFile("package.json", []byte(renderTSPackage(opts)), "module"),
		newFile("tsconfig.json", []byte(renderTSConfig()), "config"),
		newFile("verify.mjs", []byte(renderTSVerify(opts, ops)), "config"),
		newFile("README.md", []byte(renderTSReadme(opts, doc, ops, unsupported, diags, comp)), "readme"),
	}
	return files, nil
}

// tsHeader is shared by every generated TypeScript source file.
func tsHeader(docVersion, specDigest string) string {
	return "// Code generated by GoRequest sdkgen; DO NOT EDIT.\n" +
		"// generator: " + GeneratorVersion + "\n" +
		"// template: " + TemplateVersionTypeScript + "\n" +
		"// spec: OpenAPI " + docVersion + "\n" +
		"// spec-sha256: " + specDigest + "\n"
}

func renderTSTypes(doc *specDoc, comp *typeCompiler, specDigest string) string {
	var b strings.Builder
	b.WriteString(tsHeader(doc.OpenAPI, specDigest))
	b.WriteString("\n// Type model generated from the OpenAPI contract. Optional and nullable are\n// separate: `field?: T` means absent or present, `field: T | null` means\n// present and possibly null.\n\n")
	for _, m := range comp.sortedModels() {
		switch m.Kind {
		case ModelObject:
			renderTSObject(&b, m, comp)
		case ModelEnum:
			renderTSEnum(&b, m)
		case ModelUnion:
			renderTSUnion(&b, m)
		case ModelAlias:
			typ := tsTypeOf(m.Alias)
			if m.Alias != nil && m.Alias.Nullable {
				typ += " | null"
			}
			fmt.Fprintf(&b, "export type %s = %s;\n\n", m.Name, typ)
		}
	}
	return b.String()
}

func renderTSObject(b *strings.Builder, m *Model, comp *typeCompiler) {
	closed := m.Additional == nil
	if d := safeFreeText(m.Description); d != "" {
		fmt.Fprintf(b, "/** %s */\n", tsComment(d))
	}
	if closed {
		fmt.Fprintf(b, "export interface %s {\n", m.Name)
	} else {
		fmt.Fprintf(b, "export type %s = {\n", m.Name)
	}
	for _, p := range m.Properties {
		if d := safeFreeText(p.Description); d != "" {
			fmt.Fprintf(b, "  /** %s */\n", tsComment(d))
		}
		key := tsPropertyKey(p.JSONName)
		typ := tsTypeOf(p.Type)
		if p.Type != nil && p.Type.Nullable {
			typ += " | null"
		}
		if p.Required {
			fmt.Fprintf(b, "  %s: %s;\n", key, typ)
		} else {
			fmt.Fprintf(b, "  %s?: %s;\n", key, typ)
		}
	}
	if closed {
		b.WriteString("}\n\n")
		return
	}
	value := "unknown"
	if m.Additional != nil && m.Additional.Kind != TypeAny {
		value = tsTypeOf(m.Additional)
	}
	fmt.Fprintf(b, "} & Record<string, %s>;\n\n", value)
}

func renderTSEnum(b *strings.Builder, m *Model) {
	if d := safeFreeText(m.Description); d != "" {
		fmt.Fprintf(b, "/** %s */\n", tsComment(d))
	}
	fmt.Fprintf(b, "export const %s = {\n", m.Name)
	for _, v := range m.EnumValues {
		fmt.Fprintf(b, "  %s: %s,\n", tsPropertyKey(v.Name), v.Value)
	}
	b.WriteString("} as const;\n")
	fmt.Fprintf(b, "export type %s = (typeof %s)[keyof typeof %s];\n\n", m.Name, m.Name, m.Name)
}

func renderTSUnion(b *strings.Builder, m *Model) {
	if d := safeFreeText(m.Description); d != "" {
		fmt.Fprintf(b, "/** %s */\n", tsComment(d))
	}
	key := tsPropertyKey(m.Discriminator)
	parts := make([]string, 0, len(m.Variants))
	for _, v := range m.Variants {
		parts = append(parts, fmt.Sprintf("(%s & { %s: %s })", v.Model, key, strconv.Quote(v.Value)))
	}
	fmt.Fprintf(b, "export type %s = %s;\n\n", m.Name, strings.Join(parts, " | "))
}

func tsTypeOf(t *Type) string {
	if t == nil {
		return "unknown"
	}
	switch t.Kind {
	case TypeAny:
		return "unknown"
	case TypeString:
		return "string"
	case TypeInt, TypeNumber:
		return "number"
	case TypeBool:
		return "boolean"
	case TypeArray:
		return "Array<" + tsTypeOf(t.Items) + ">"
	case TypeMap:
		return "Record<string, " + tsTypeOf(t.MapValue) + ">"
	case TypeModel:
		return t.Ref
	default:
		return "unknown"
	}
}

func tsPropertyKey(name string) string {
	if isASCIIIdentifier(name) {
		return name
	}
	return strconv.Quote(name)
}

func isASCIIIdentifier(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		ok := r == '_' || r == '$' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (i > 0 && r >= '0' && r <= '9')
		if !ok {
			return false
		}
	}
	return true
}

func tsComment(s string) string {
	s = strings.ReplaceAll(s, "*/", "* /")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}

const tsErrorsTemplate = `// Code generated by GoRequest sdkgen; DO NOT EDIT.

// SDKError is the base class for generated SDK failures.
export class SDKError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "SDKError";
  }
}

// ApiError reports a non-2xx response with the real status, headers, bounded
// body and, when the contract declares a JSON model for the status, the
// decoded value. The client never retries.
export class ApiError extends SDKError {
  readonly status: number;
  readonly headers: Headers;
  readonly body: Uint8Array;
  readonly data: unknown;

  constructor(status: number, headers: Headers, body: Uint8Array, data?: unknown) {
    super("HTTP " + status);
    this.name = "ApiError";
    this.status = status;
    this.headers = headers;
    this.body = body;
    this.data = data;
  }
}

// TimeoutError reports that the client timeout elapsed.
export class TimeoutError extends SDKError {
  constructor(timeoutMs: number) {
    super("request timed out after " + timeoutMs + " ms");
    this.name = "TimeoutError";
  }
}

// ResponseTooLargeError reports that the bounded response read was exceeded.
export class ResponseTooLargeError extends SDKError {
  constructor(maxBytes: number) {
    super("response body exceeds " + maxBytes + " bytes");
    this.name = "ResponseTooLargeError";
  }
}
`

func renderTSErrors() string { return tsErrorsTemplate }

const tsClientTemplate = `// Code generated by GoRequest sdkgen; DO NOT EDIT.
{{HEADER}}

import { ApiError, ResponseTooLargeError, SDKError, TimeoutError } from "./errors.ts";

export const DEFAULT_TIMEOUT_MS = 30_000;
export const DEFAULT_MAX_RESPONSE_BYTES = 8 * 1024 * 1024;

export interface QueryEntry {
  name: string;
  value: string;
}

export interface RawResponse {
  status: number;
  headers: Headers;
  body: Uint8Array;
}

export interface RequestSpec {
  method: string;
  path: string;
  query?: QueryEntry[];
  headers?: Record<string, string>;
  body?: string;
  signal?: AbortSignal;
}

export interface ClientOptions {
  /** Absolute http(s) base URL. Required. */
  baseURL: string;
  /** Fetch implementation. Defaults to globalThis.fetch. */
  fetch?: typeof fetch;
  /** Called for every request; supply credentials here. Never embedded. */
  auth?: (req: Request) => void | Promise<void>;
  /** Request timeout in milliseconds; defaults to 30s. */
  timeoutMs?: number;
  /** Bounded response read; defaults to 8 MiB. */
  maxResponseBytes?: number;
  /** Headers merged into every request. */
  defaultHeaders?: Record<string, string>;
}

// Client is a generated HTTP client. It never retries and never executes
// generated code. TLS verification follows the platform fetch defaults.
export class Client {
  readonly baseURL: string;
  readonly auth: ((req: Request) => void | Promise<void>) | undefined;
  readonly timeoutMs: number;
  readonly maxResponseBytes: number;
  readonly defaultHeaders: Record<string, string>;
  readonly origin: string;
  readonly basePath: string;
  readonly baseQuery: string;
  readonly fetchImpl: typeof fetch;

  constructor(options: ClientOptions) {
    const raw = options.baseURL.trim();
    if (raw === "") {
      throw new SDKError("baseURL is required");
    }
    const parsed = new URL(raw);
    if (parsed.protocol !== "http:" && parsed.protocol !== "https:") {
      throw new SDKError("baseURL must use http or https");
    }
    const impl = options.fetch ?? globalThis.fetch;
    if (typeof impl !== "function") {
      throw new SDKError("fetch is not available; supply ClientOptions.fetch");
    }
    this.baseURL = raw;
    this.origin = parsed.origin;
    this.basePath = parsed.pathname.replace(/\/+$/, "");
    this.baseQuery = parsed.search ? parsed.search.slice(1) : "";
    this.fetchImpl = impl;
    this.auth = options.auth;
    this.timeoutMs = options.timeoutMs !== undefined && options.timeoutMs > 0 ? options.timeoutMs : DEFAULT_TIMEOUT_MS;
    this.maxResponseBytes = options.maxResponseBytes !== undefined && options.maxResponseBytes > 0 ? options.maxResponseBytes : DEFAULT_MAX_RESPONSE_BYTES;
    this.defaultHeaders = { ...(options.defaultHeaders ?? {}) };
  }

  async request(spec: RequestSpec): Promise<RawResponse> {
    if (spec.path.includes("{") || spec.path.includes("}")) {
      throw new SDKError("unresolved path template: " + spec.path);
    }
    const search = new URLSearchParams(this.baseQuery);
    for (const entry of spec.query ?? []) {
      search.append(entry.name, entry.value);
    }
    const qs = search.toString();
    const url = this.origin + this.basePath + spec.path + (qs === "" ? "" : "?" + qs);
    const headers: Record<string, string> = { ...this.defaultHeaders };
    for (const [name, value] of Object.entries(spec.headers ?? {})) {
      validateHeader(name, value);
      headers[name] = value;
    }
    if (spec.body !== undefined && !hasHeader(headers, "content-type")) {
      headers["Content-Type"] = "application/json";
    }

    const controller = new AbortController();
    let timedOut = false;
    const timer = setTimeout(() => {
      timedOut = true;
      controller.abort();
    }, this.timeoutMs);
    const userSignal = spec.signal;
    const onAbort = () => controller.abort();
    if (userSignal) {
      if (userSignal.aborted) {
        controller.abort();
      } else {
        userSignal.addEventListener("abort", onAbort, { once: true });
      }
    }

    try {
      const req = new Request(url, {
        method: spec.method,
        headers,
        body: spec.body,
        signal: controller.signal,
      });
      if (this.auth) {
        await this.auth(req);
      }
      const res = await this.fetchImpl(req);
      const body = await readBounded(res, this.maxResponseBytes);
      return { status: res.status, headers: res.headers, body };
    } catch (err) {
      if (timedOut) {
        throw new TimeoutError(this.timeoutMs);
      }
      throw err;
    } finally {
      clearTimeout(timer);
      if (userSignal) {
        userSignal.removeEventListener("abort", onAbort);
      }
    }
  }

  decodeJSON<T>(raw: RawResponse): T {
    if (raw.body.byteLength === 0) {
      throw new SDKError("empty response body for a declared JSON response");
    }
    const text = new TextDecoder().decode(raw.body);
    return JSON.parse(text) as T;
  }
}

// encodePathValue percent-encodes one path parameter using the same rules as
// Go's net/url.PathEscape (mode encodePathSegment), so both backends produce
// the same URL for the same input.
export function encodePathValue(value: string): string {
  const encoder = new TextEncoder();
  let out = "";
  for (const ch of value) {
    const code = ch.codePointAt(0) ?? 0;
    const safe =
      (code >= 48 && code <= 57) ||
      (code >= 65 && code <= 90) ||
      (code >= 97 && code <= 122) ||
      ch === "-" || ch === "_" || ch === "." || ch === "~" ||
      ch === "$" || ch === "&" || ch === "+" || ch === ":" || ch === "=" || ch === "@";
    if (safe) {
      out += ch;
      continue;
    }
    for (const byte of encoder.encode(ch)) {
      out += "%" + byte.toString(16).toUpperCase().padStart(2, "0");
    }
  }
  return out;
}

function hasHeader(headers: Record<string, string>, name: string): boolean {
  const lower = name.toLowerCase();
  for (const key of Object.keys(headers)) {
    if (key.toLowerCase() === lower) {
      return true;
    }
  }
  return false;
}

function validateHeader(name: string, value: string): void {
  if (name === "" || /[\r\n:]/.test(name)) {
    throw new SDKError("invalid header name: " + name);
  }
  if (/[\r\n]/.test(value)) {
    throw new SDKError("invalid value for header " + name);
  }
}

async function readBounded(res: Response, maxBytes: number): Promise<Uint8Array> {
  if (!res.body) {
    return new Uint8Array(0);
  }
  const reader = res.body.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  for (;;) {
    const next = await reader.read();
    if (next.done) {
      break;
    }
    if (next.value) {
      total += next.value.byteLength;
      if (total > maxBytes) {
        await reader.cancel();
        throw new ResponseTooLargeError(maxBytes);
      }
      chunks.push(next.value);
    }
  }
  const out = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    out.set(chunk, offset);
    offset += chunk.byteLength;
  }
  return out;
}
`

func renderTSClient(opts Options, doc *specDoc, specDigest string) string {
	out := strings.ReplaceAll(tsClientTemplate, "{{HEADER}}", strings.TrimSpace(tsHeader(doc.OpenAPI, specDigest)))
	return out
}

func renderTSOperations(opts Options, doc *specDoc, ops []Operation, comp *typeCompiler, specDigest string) string {
	var b strings.Builder
	b.WriteString(tsHeader(doc.OpenAPI, specDigest))
	b.WriteString("\nimport { ApiError, SDKError } from \"./errors.ts\";\n")
	b.WriteString("import { Client, encodePathValue, type QueryEntry, type RawResponse } from \"./client.ts\";\n")
	modelNames := make([]string, 0, len(comp.models))
	for name := range comp.models {
		modelNames = append(modelNames, name)
	}
	sort.Strings(modelNames)
	if len(modelNames) > 0 {
		fmt.Fprintf(&b, "import type { %s } from \"./types.ts\";\n", strings.Join(modelNames, ", "))
	}
	b.WriteString("\nexport interface OperationOptions {\n  signal?: AbortSignal;\n}\n\n")

	for _, op := range ops {
		renderTSOperation(&b, op, comp)
	}
	return b.String()
}

func renderTSOperation(b *strings.Builder, op Operation, comp *typeCompiler) {
	inputType := op.GoName + "Input"
	resultType := op.GoName + "Result"
	fnName := tsFunctionName(op.GoName)

	// Input interface.
	fmt.Fprintf(b, "export interface %s {\n", inputType)
	paramFields := tsParamFields(op.paramsList)
	for i, p := range op.paramsList {
		name := paramFields[i]
		typ := tsParamType(p)
		optional := !p.Required
		if optional {
			fmt.Fprintf(b, "  %s?: %s;\n", name, typ)
		} else {
			fmt.Fprintf(b, "  %s: %s;\n", name, typ)
		}
	}
	if op.body != nil && op.BodyType != "" {
		required := op.body.Required
		if required {
			fmt.Fprintf(b, "  body: %s;\n", op.BodyType)
		} else {
			fmt.Fprintf(b, "  body?: %s;\n", op.BodyType)
		}
	}
	if op.body != nil {
		b.WriteString("  /** Raw JSON body escape hatch; ignored when body is set. */\n  rawBody?: string;\n")
	}
	b.WriteString("}\n\n")

	// Result interface.
	dataTypes := make([]string, 0, len(op.responseTypes))
	for _, r := range op.responseTypes {
		if r.Type != nil && r.Type.Kind == TypeModel {
			dataTypes = append(dataTypes, r.Type.Ref)
		}
	}
	fmt.Fprintf(b, "export interface %s {\n", resultType)
	b.WriteString("  status: number;\n  headers: Headers;\n  body: Uint8Array;\n")
	if len(dataTypes) > 0 {
		fmt.Fprintf(b, "  data?: %s;\n", strings.Join(dataTypes, " | "))
	} else {
		b.WriteString("  data?: unknown;\n")
	}
	b.WriteString("}\n\n")

	// Operation function.
	if s := safeFreeText(op.Summary); s != "" {
		fmt.Fprintf(b, "/** %s */\n", tsComment(s))
	}
	fmt.Fprintf(b, "export async function %s(client: Client, input: %s, options?: OperationOptions): Promise<%s> {\n", fnName, inputType, resultType)
	// Required-path and required-parameter checks.
	for i, p := range op.paramsList {
		if !p.Required {
			continue
		}
		fmt.Fprintf(b, "  if (input.%s === undefined || input.%s === null) {\n", paramFields[i], paramFields[i])
		fmt.Fprintf(b, "    throw new SDKError(%q);\n  }\n", p.Name+" is required")
	}
	if op.body != nil && op.body.Required {
		b.WriteString("  if (input.body === undefined && input.rawBody === undefined) {\n")
		fmt.Fprintf(b, "    throw new SDKError(%q);\n  }\n", "body is required")
	}
	if op.body != nil {
		b.WriteString("  const body = input.body !== undefined ? JSON.stringify(input.body) : input.rawBody;\n")
	}

	// Path.
	fmt.Fprintf(b, "  let path = %s;\n", strconv.Quote(op.Path))
	for _, p := range op.paramsList {
		if p.In != "path" {
			continue
		}
		field := inputFieldFor(op.paramsList, p.Name)
		if p.Array {
			fmt.Fprintf(b, "  path = path.replace(%q, input.%s.map((v) => encodePathValue(String(v))).join(\",\"));\n",
				"{"+p.Name+"}", field)
		} else {
			fmt.Fprintf(b, "  path = path.replace(%q, encodePathValue(String(input.%s)));\n",
				"{"+p.Name+"}", field)
		}
	}

	// Query.
	b.WriteString("  const query: QueryEntry[] = [];\n")
	for _, p := range op.paramsList {
		if p.In != "query" {
			continue
		}
		field := inputFieldFor(op.paramsList, p.Name)
		expr := "input." + field
		if !p.Required {
			fmt.Fprintf(b, "  if (%s !== undefined) {\n", expr)
		} else {
			b.WriteString("  {\n")
		}
		if p.Array {
			switch {
			case p.Explode && (p.Style == "" || p.Style == "form"):
				fmt.Fprintf(b, "    for (const value of %s) {\n      query.push({ name: %q, value: String(value) });\n    }\n", expr, p.Name)
			default:
				sep := ","
				switch p.Style {
				case "spacedelimited":
					sep = " "
				case "pipedelimited":
					sep = "|"
				}
				fmt.Fprintf(b, "    query.push({ name: %q, value: %s.map((v) => String(v)).join(%q) });\n", p.Name, expr, sep)
			}
		} else {
			fmt.Fprintf(b, "    query.push({ name: %q, value: String(%s) });\n", p.Name, expr)
		}
		b.WriteString("  }\n")
	}

	// Headers.
	b.WriteString("  const headers: Record<string, string> = {};\n")
	for _, p := range op.paramsList {
		if p.In != "header" {
			continue
		}
		field := inputFieldFor(op.paramsList, p.Name)
		expr := "input." + field
		if !p.Required {
			fmt.Fprintf(b, "  if (%s !== undefined) {\n", expr)
		} else {
			b.WriteString("  {\n")
		}
		if p.Array {
			fmt.Fprintf(b, "    headers[%q] = %s.map((v) => String(v)).join(\",\");\n", p.Name, expr)
		} else {
			fmt.Fprintf(b, "    headers[%q] = String(%s);\n", p.Name, expr)
		}
		b.WriteString("  }\n")
	}

	b.WriteString("  const raw = await client.request({\n")
	fmt.Fprintf(b, "    method: %q,\n    path,\n    query,\n    headers,\n", op.Method)
	if op.body != nil {
		b.WriteString("    body,\n")
	}
	b.WriteString("    signal: options?.signal,\n  });\n")

	hasDecode := false
	for _, r := range op.responseTypes {
		if r.Type != nil && r.Type.Kind == TypeModel {
			hasDecode = true
		}
	}
	if hasDecode {
		fmt.Fprintf(b, "  const data = decode%s(client, raw);\n", op.GoName)
	} else {
		b.WriteString("  const data = undefined;\n")
	}
	b.WriteString("  if (raw.status >= 200 && raw.status < 300) {\n")
	b.WriteString("    return { status: raw.status, headers: raw.headers, body: raw.body, data };\n  }\n")
	b.WriteString("  throw new ApiError(raw.status, raw.headers, raw.body, data);\n}\n\n")

	if hasDecode {
		renderTSDecode(b, op)
	}
}

func renderTSDecode(b *strings.Builder, op Operation) {
	dataTypes := make([]string, 0, len(op.responseTypes))
	for _, r := range op.responseTypes {
		if r.Type != nil && r.Type.Kind == TypeModel {
			dataTypes = append(dataTypes, r.Type.Ref)
		}
	}
	dataType := "unknown"
	if len(dataTypes) > 0 {
		dataType = strings.Join(dataTypes, " | ")
	}
	fmt.Fprintf(b, "function decode%s(client: Client, raw: RawResponse): %s | undefined {\n", op.GoName, dataType)
	b.WriteString("  switch (raw.status) {\n")
	var rangeCases []responseType
	var defaultCase *responseType
	for _, r := range op.responseTypes {
		if r.Type == nil || r.Type.Kind != TypeModel {
			continue
		}
		s := strings.ToLower(strings.TrimSpace(r.Status))
		if s == "default" {
			cp := r
			defaultCase = &cp
			continue
		}
		if n, err := strconv.Atoi(s); err == nil {
			fmt.Fprintf(b, "    case %d:\n      return client.decodeJSON<%s>(raw);\n", n, r.Type.Ref)
			continue
		}
		rangeCases = append(rangeCases, r)
	}
	b.WriteString("  }\n")
	b.WriteString("  const statusClass = Math.trunc(raw.status / 100);\n")
	for _, r := range rangeCases {
		s := strings.ToLower(strings.TrimSpace(r.Status))
		if len(s) != 3 || s[0] < '1' || s[0] > '5' || (s[1] != 'x' && s[2] != 'x') {
			continue
		}
		fmt.Fprintf(b, "  if (statusClass === %c) {\n    return client.decodeJSON<%s>(raw);\n  }\n", s[0], r.Type.Ref)
	}
	if defaultCase != nil {
		fmt.Fprintf(b, "  return client.decodeJSON<%s>(raw);\n", defaultCase.Type.Ref)
	} else {
		b.WriteString("  return undefined;\n")
	}
	b.WriteString("}\n\n")
}

func tsParamFields(params []paramSpec) []string {
	used := map[string]bool{}
	out := make([]string, len(params))
	for i, p := range params {
		base := lowerCamelIdentifier(p.Name)
		if base == "" {
			base = "param"
		}
		name := base
		for n := 2; used[name]; n++ {
			name = base + strconv.Itoa(n)
		}
		used[name] = true
		out[i] = name
	}
	return out
}

func inputFieldFor(params []paramSpec, jsonName string) string {
	fields := tsParamFields(params)
	for i, p := range params {
		if p.Name == jsonName {
			return fields[i]
		}
	}
	return lowerCamelIdentifier(jsonName)
}

func lowerCamelIdentifier(raw string) string {
	words := splitWords(raw)
	if len(words) == 0 {
		return ""
	}
	var b strings.Builder
	first := []rune(words[0])
	b.WriteString(strings.ToLower(string(first[0])))
	if len(first) > 1 {
		b.WriteString(string(first[1:]))
	}
	for _, w := range words[1:] {
		b.WriteString(titleWord(w))
	}
	out := b.String()
	if out == "" {
		return "param"
	}
	if out[0] >= '0' && out[0] <= '9' {
		out = "p" + out
	}
	return out
}

func tsFunctionName(goName string) string {
	name := lowerCamelIdentifier(goName)
	if name == "" {
		return "call"
	}
	switch name {
	case "client", "request", "fetch", "encodePathValue", "decodeJSON":
		return name + "Op"
	}
	return name
}

func tsParamType(p paramSpec) string {
	base := "string"
	switch p.Kind {
	case kindInt64, kindFloat64:
		base = "number"
	case kindBool:
		base = "boolean"
	}
	if p.Array {
		return "Array<" + base + ">"
	}
	return base
}

func hasPathParam(params []paramSpec) bool {
	for _, p := range params {
		if p.In == "path" {
			return true
		}
	}
	return false
}

