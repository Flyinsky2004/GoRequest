func renderTSPackage(opts Options) string {
	name := strings.ToLower(opts.PackageName)
	var b strings.Builder
	for _, r := range name {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteRune('-')
		}
	}
	pkg := strings.Trim(b.String(), "-_")
	if pkg == "" {
		pkg = "generated-sdk"
	}
	obj := map[string]any{
		"name":    pkg,
		"version": "0.0.0",
		"private": true,
		"type":    "module",
		"types":   "./index.ts",
		"exports": map[string]string{".": "./index.ts"},
		"scripts": map[string]string{
			"typecheck": "tsc --noEmit",
			"verify":    "node --experimental-strip-types verify.mjs",
		},
	}
	data, _ := json.MarshalIndent(obj, "", "  ")
	return string(append(data, '\n'))
}

