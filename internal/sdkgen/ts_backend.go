func renderTSVerify(opts Options, ops []Operation) string {
	var b strings.Builder
	b.WriteString("// Generated manual verification entry. It sends nothing unless\n// GOREQUEST_VERIFY_BASE_URL points at a loopback or test server.\n")
	b.WriteString("import { Client } from \"./client.ts\";\n")
	var target *Operation
	for i := range ops {
		if ops[i].Method == "GET" && len(ops[i].paramsList) == 0 && ops[i].body == nil {
			target = &ops[i]
			break
		}
	}
	if target != nil {
		fmt.Fprintf(&b, "import { %s } from \"./operations.ts\";\n", tsFunctionName(target.GoName))
	}
	b.WriteString("\nconst base = process.env.GOREQUEST_VERIFY_BASE_URL;\n")
	b.WriteString("if (!base) {\n  console.error(\"Set GOREQUEST_VERIFY_BASE_URL to a loopback/test base URL; no request was sent.\");\n  process.exit(2);\n}\n")
	b.WriteString("const client = new Client({ baseURL: base });\n")
	if target != nil {
		fmt.Fprintf(&b, "const result = await %s(client, {});\n", tsFunctionName(target.GoName))
		b.WriteString("console.log(\"status\", result.status, \"bytes\", result.body.byteLength);\n")
	} else {
		b.WriteString("console.log(\"SDK constructed. No parameterless GET operation exists to verify automatically.\");\n")
	}
	return b.String()
}

