// renderGoFiles renders the complete Go backend file set.
func renderGoFiles(opts Options, doc *specDoc, ops []Operation, unsupported []UnsupportedOperation, diags []Diagnostic, specDigest string, comp *typeCompiler) ([]File, error) {
	var files []File

	clientSrc, err := newSourceFile("client.go", renderClient(opts, doc, specDigest), "source")
	if err != nil {
		return nil, err
	}
	files = append(files, clientSrc)

	models := comp.sortedModels()
	if len(models) > 0 {
		modelSrc, err := newSourceFile("models.go", renderGoModels(opts, comp), "source")
		if err != nil {
			return nil, err
		}
		files = append(files, modelSrc)
	}

	if len(ops) > 0 {
		opsSrc, err := newSourceFile("operations.go", renderOperations(opts, ops, comp), "source")
		if err != nil {
			return nil, err
		}
		files = append(files, opsSrc)
	}

	readme := newFile("README.md", []byte(renderGoReadme(opts, doc, ops, unsupported, diags, models)), "readme")
	files = append(files, readme)

	gomod := newFile("go.mod", []byte("module "+opts.ModulePath+"\n\ngo 1.21\n"), "module")
	files = append(files, gomod)
	return files, nil
}

