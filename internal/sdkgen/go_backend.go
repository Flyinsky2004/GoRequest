// safeTitle is a conservative defense-in-depth guard: the snapshot is expected
// to be redacted already, but free-form text that still looks like a credential
// or a template placeholder is dropped rather than leaking into generated
// output.
func safeTitle(title, fallback string) string {
	if t := safeFreeText(title); t != "" {
		return t
	}
	return fallback
}

// safeFreeText returns text unless it looks like a credential or unresolved
// template placeholder.
func safeFreeText(text string) string {
	t := strings.TrimSpace(text)
	if t == "" {
		return ""
	}
	lower := strings.ToLower(t)
	for _, marker := range []string{"{{", "}}", "sk-", "bearer ", "basic ", "token=", "api_key=", "apikey=", "password="} {
		if strings.Contains(lower, marker) {
			return ""
		}
	}
	return t
}

// orderedModelNames is used by tests and diagnostics.
func orderedModelNames(models []*Model) []string {
	out := make([]string, len(models))
	for i, m := range models {
		out[i] = m.Name
	}
	sort.Strings(out)
	return out
}

