// --- block tree ---------------------------------------------------------------

// blockNode is a Markdown block plus its tree children. The parser returns
// blocks in pre-order with byte spans; nesting is reconstructed by interval
// containment so no second Markdown parser exists.
type blockNode struct {
	block markdown.Block
	idx   int // index of the block within the parser's block list
	line  int // 1-based source line of the block start
	child []*blockNode
}

func buildBlockTree(src string, blocks []markdown.Block) []*blockNode {
	var roots []*blockNode
	var stack []*blockNode
	for i, b := range blocks {
		line, _ := LineColAt(src, b.Start)
		n := &blockNode{block: b, idx: i, line: line}
		for len(stack) > 0 {
			top := stack[len(stack)-1]
			contained := b.Start >= top.block.Start && b.End <= top.block.End &&
				canContainBlock(top.block.Kind, b.Kind)
			if contained {
				break
			}
			stack = stack[:len(stack)-1]
		}
		if len(stack) == 0 {
			roots = append(roots, n)
		} else {
			parent := stack[len(stack)-1]
			parent.child = append(parent.child, n)
		}
		stack = append(stack, n)
	}
	return roots
}

func canContainBlock(parent, child markdown.Kind) bool {
	switch parent {
	case markdown.List:
		return child == markdown.Item
	case markdown.Table:
		return child == markdown.TableRow
	case markdown.TableRow:
		return child == markdown.TableCell
	case markdown.Item, markdown.Quote, markdown.FootnoteDefinition:
		switch child {
		case markdown.Item, markdown.TableRow, markdown.TableCell:
			return false
		}
		return true
	}
	return false
}

// --- renderer -----------------------------------------------------------------

type htmlRenderer struct {
	src       string
	opts      RenderOptions
	doc       *markdown.Document
	b         strings.Builder
	cardLines map[int]string
}

func (r *htmlRenderer) writeChildren(nodes []*blockNode) {
	for _, n := range nodes {
		r.writeBlock(n)
	}
}

func (r *htmlRenderer) inlinesOf(n *blockNode) []markdown.Inline {
	return r.doc.Inlines(n.idx)
}

func (r *htmlRenderer) writeBlock(n *blockNode) {
	b := n.block
	switch b.Kind {
	case markdown.Heading:
		level := b.Level
		if level < 1 {
			level = 1
		}
		if level > 6 {
			level = 6
		}
		tag := "h" + strconv.Itoa(level)
		id, cls := r.headingAttrs(n)
		r.b.WriteString("<" + tag)
		if id != "" {
			r.b.WriteString(" id=\"" + html.EscapeString(id) + "\"")
		}
		if cls != "" {
			r.b.WriteString(" class=\"" + html.EscapeString(cls) + "\"")
		}
		r.b.WriteString(">")
		in := r.inlinesOf(n)
		r.writeInlineSpan(in, 0, len(in))
		r.b.WriteString("</" + tag + ">\n")
	case markdown.Paragraph:
		in := r.inlinesOf(n)
		if len(in) == 0 {
			return
		}
		r.b.WriteString("<p>")
		r.writeInlineSpan(in, 0, len(in))
		r.b.WriteString("</p>\n")
	case markdown.CodeBlock:
		r.writeCodeBlock(n)
	case markdown.Quote:
		r.b.WriteString("<blockquote>\n")
		r.writeChildren(n.child)
		r.b.WriteString("</blockquote>\n")
	case markdown.List:
		r.writeList(n)
	case markdown.ThematicBreak:
		r.b.WriteString("<hr>\n")
	case markdown.HTMLBlock:
		r.b.WriteString("<pre class=\"docgen-html-source\">")
		r.b.WriteString(html.EscapeString(r.src[b.Start:b.End]))
		r.b.WriteString("</pre>\n")
	case markdown.Table:
		r.writeTable(n)
	case markdown.Item:
		// Items are children of List; a stray item renders its children.
		r.writeChildren(n.child)
	case markdown.TableRow, markdown.TableCell:
		// Defensive: content outside a table renders as text.
		if in := r.inlinesOf(n); len(in) > 0 {
			r.b.WriteString("<p>")
			r.writeInlineSpan(in, 0, len(in))
			r.b.WriteString("</p>\n")
		}
		r.writeChildren(n.child)
	case markdown.FootnoteDefinition:
		r.b.WriteString("<div class=\"footnote\">")
		r.writeChildren(n.child)
		r.b.WriteString("</div>\n")
	case markdown.MathBlock:
		r.b.WriteString("<pre class=\"docgen-math\">")
		r.b.WriteString(html.EscapeString(strings.TrimSpace(r.src[b.Start:b.End])))
		r.b.WriteString("</pre>\n")
	}
}

func (r *htmlRenderer) headingAttrs(n *blockNode) (id, class string) {
	in := r.inlinesOf(n)
	if anchor, ok := r.cardLines[n.line]; ok {
		return anchor, "docgen-card"
	}
	return core.GitHubHeadingSlug(markdown.PlainText(in)), ""
}

func (r *htmlRenderer) writeCodeBlock(n *blockNode) {
	b := n.block
	lang := b.Language()
	if strings.EqualFold(lang, "mermaid") {
		r.writeMermaid(b)
		return
	}
	r.writeCodeSource(lang, r.codeText(b))
}

// writeCodeSource writes one inert code block with its language class.
func (r *htmlRenderer) writeCodeSource(lang, code string) {
	r.b.WriteString("<pre><code")
	if lang != "" {
		r.b.WriteString(" class=\"language-" + html.EscapeString(lang) + "\"")
	}
	r.b.WriteString(">")
	r.b.WriteString(html.EscapeString(code))
	r.b.WriteString("</code></pre>\n")
}

// writeMermaid renders a supported diagram as a self-contained inline SVG
// and keeps the source in an inert <details> block. Unsupported syntax
// keeps the source and states the exact reason; it never draws a partial
// picture.
func (r *htmlRenderer) writeMermaid(b markdown.Block) {
	source := r.codeText(b)
	fenceLine := 1 + strings.Count(r.src[:b.Start], "\n")
	if !r.opts.Diagram.Disable {
		scene, d := diagram.Render(context.Background(), source, diagram.Options{FontSize: r.opts.Diagram.FontSize})
		if d == nil {
			limits := diagram.DefaultLimits
			svg, sd := diagram.RenderSVG(scene, r.opts.Diagram.Theme, limits)
			if sd == nil {
				r.b.WriteString("<figure class=\"docgen-diagram\">\n")
				r.b.WriteString(svg)
				r.b.WriteString("<figcaption>" + html.EscapeString(diagramCaption(scene)) + "</figcaption>\n")
				r.b.WriteString("<details class=\"docgen-diagram-source\"><summary>Mermaid source</summary>\n")
				r.writeCodeSource("mermaid", source)
				r.b.WriteString("</details>\n</figure>\n")
				return
			}
			d = sd
		}
		// Report the line in document coordinates, not within the fence.
		at := *d
		if at.Line > 0 {
			at.Line += fenceLine
		}
		r.b.WriteString("<div class=\"docgen-mermaid-note\">" + html.EscapeString(r.opts.MermaidNote+" Reason: "+at.Error()) + "</div>\n")
		r.writeCodeSource("mermaid", source)
		return
	}
	r.b.WriteString("<div class=\"docgen-mermaid-note\">" + html.EscapeString(r.opts.MermaidNote) + "</div>\n")
	r.writeCodeSource("mermaid", source)
}

func diagramCaption(s *diagram.Scene) string {
	if s.Kind == diagram.KindSequence {
		return "Mermaid sequenceDiagram (offline subset: participants, messages, notes)"
	}
	return "Mermaid flowchart " + strings.TrimPrefix(s.Title, "flowchart ") + " (offline subset)"
}

// codeText extracts the literal code content, stripping the fences of a
// fenced block and the 4-space indent of an indented block.
func (r *htmlRenderer) codeText(b markdown.Block) string {
	raw := r.src[b.Start:b.End]
	lines := strings.Split(strings.TrimRight(raw, "\n"), "\n")
	if b.Fenced {
		return fencedCodeText(lines)
	}
	for i, line := range lines {
		if strings.HasPrefix(line, "    ") {
			lines[i] = line[4:]
		} else if strings.HasPrefix(line, "\t") {
			lines[i] = line[1:]
		}
	}
	return strings.Join(lines, "\n")
}

// fencedCodeText drops the opening fence and, when the block span includes
// it, the closing fence. The project Markdown parser ends a fenced block at
// the last content line, so only the opening fence is guaranteed.
func fencedCodeText(lines []string) string {
	if len(lines) == 0 {
		return ""
	}
	lines = lines[1:]
	if len(lines) > 0 && isClosingFence(lines[len(lines)-1]) {
		lines = lines[:len(lines)-1]
	}
	return strings.Join(lines, "\n")
}

func isClosingFence(line string) bool {
	trimmed := strings.TrimSpace(line)
	return strings.HasPrefix(trimmed, "```") || strings.HasPrefix(trimmed, "~~~")
}

func (r *htmlRenderer) writeList(n *blockNode) {
	tag, closeTag := "ul", "</ul>"
	if n.block.Ordered {
		tag, closeTag = "ol", "</ol>"
	}
	r.b.WriteString("<" + tag + ">\n")
	for _, c := range n.child {
		if c.block.Kind == markdown.Item {
			r.writeItem(c)
			continue
		}
		r.writeBlock(c)
	}
	r.b.WriteString(closeTag + "\n")
}

// writeItem renders one list item. Task items keep their state as a visible
// glyph - no form controls, staying inert.
func (r *htmlRenderer) writeItem(n *blockNode) {
	switch n.block.Task {
	case markdown.TaskChecked:
		r.b.WriteString("<li class=\"task-checked\">&#9745; ")
	case markdown.TaskUnchecked:
		r.b.WriteString("<li class=\"task-unchecked\">&#9744; ")
	default:
		r.b.WriteString("<li>")
		if len(n.child) > 1 {
			r.b.WriteString("\n")
		}
	}
	if len(n.child) == 1 && n.child[0].block.Kind == markdown.Paragraph {
		in := r.inlinesOf(n.child[0])
		r.writeInlineSpan(in, 0, len(in))
		r.b.WriteString("</li>\n")
		return
	}
	wroteLead := false
	for _, c := range n.child {
		if c.block.Kind == markdown.Paragraph && !wroteLead {
			in := r.inlinesOf(c)
			r.writeInlineSpan(in, 0, len(in))
			r.b.WriteString("\n")
			wroteLead = true
			continue
		}
		r.writeBlock(c)
	}
	r.b.WriteString("</li>\n")
}

// writeTable renders a GFM table. The flat parser maps both the header row
// and body rows to TableRow; the extension's semantics put the header first,
// so the first row renders as <thead> and the rest as body rows.
func (r *htmlRenderer) writeTable(n *blockNode) {
	align := n.block.Align
	r.b.WriteString("<table>\n")
	rows := 0
	for _, c := range n.child {
		if c.block.Kind != markdown.TableRow {
			// Unexpected content inside a table renders after the rows.
			r.writeBlock(c)
			continue
		}
		header := rows == 0
		if header {
			r.b.WriteString("<thead><tr>")
		} else if rows == 1 {
			r.b.WriteString("<tbody>\n<tr>")
		} else {
			r.b.WriteString("<tr>")
		}
		for i, cell := range c.child {
			tag := "td"
			if header {
				tag = "th"
			}
			r.b.WriteString("<" + tag + r.alignAttr(align, i) + ">")
			in := r.inlinesOf(cell)
			r.writeInlineSpan(in, 0, len(in))
			r.b.WriteString("</" + tag + ">")
		}
		if header {
			r.b.WriteString("</tr></thead>\n")
		} else {
			r.b.WriteString("</tr>\n")
		}
		rows++
	}
	if rows > 1 {
		r.b.WriteString("</tbody>\n")
	}
	r.b.WriteString("</table>\n")
}

func (r *htmlRenderer) alignAttr(align []markdown.Alignment, i int) string {
	if i < 0 || i >= len(align) {
		return ""
	}
	switch align[i] {
	case markdown.AlignLeft:
		return " align=\"left\""
	case markdown.AlignRight:
		return " align=\"right\""
	case markdown.AlignCenter:
		return " align=\"center\""
	}
	return ""
}

// --- inlines ------------------------------------------------------------------

// writeInlineSpan renders run[from:to]. The parser flattens nested inline
// markup into an opener (carrying the full span) followed by its children; the
// closer is implicit, so nesting is reconstructed by span containment.
func (r *htmlRenderer) writeInlineSpan(run []markdown.Inline, from, to int) {
	for i := from; i < to; i++ {
		inl := run[i]
		switch inl.Kind {
		case markdown.Text:
			r.b.WriteString(html.EscapeString(inl.Text))
		case markdown.SoftBreak:
			r.b.WriteString("\n")
		case markdown.LineBreak:
			r.b.WriteString("<br>\n")
		case markdown.Emphasis:
			end := r.childClose(run, i, to, inl)
			r.b.WriteString("<em>")
			r.writeInlineSpan(run, i+1, end)
			r.b.WriteString("</em>")
			i = end - 1
		case markdown.Strong:
			end := r.childClose(run, i, to, inl)
			r.b.WriteString("<strong>")
			r.writeInlineSpan(run, i+1, end)
			r.b.WriteString("</strong>")
			i = end - 1
		case markdown.Strikethrough:
			end := r.childClose(run, i, to, inl)
			r.b.WriteString("<del>")
			r.writeInlineSpan(run, i+1, end)
			r.b.WriteString("</del>")
			i = end - 1
		case markdown.Code:
			r.b.WriteString("<code>" + html.EscapeString(inl.Text) + "</code>")
		case markdown.HTML:
			r.b.WriteString("<code class=\"docgen-html-source\">" + html.EscapeString(inl.Text) + "</code>")
		case markdown.Math:
			r.b.WriteString("<code class=\"docgen-math\">" + html.EscapeString(inl.Text) + "</code>")
		case markdown.FootnoteRef:
			r.b.WriteString("<sup class=\"footnote-ref\">" + html.EscapeString(inl.Text) + "</sup>")
		case markdown.Link:
			r.writeLink(run, i, to)
			i = r.childClose(run, i, to, inl) - 1
		case markdown.Image:
			r.writeImage(run, i, to)
			i = r.childClose(run, i, to, inl) - 1
		}
	}
}

// childClose returns the exclusive end index of an opener's children within
// run[from:to]: children are the inlines that follow the opener and whose
// span stays inside the opener's span. An opener with no children in the
// slice yields i+1 (empty content).
func (r *htmlRenderer) childClose(run []markdown.Inline, i, to int, opener markdown.Inline) int {
	end := i + 1
	for j := i + 1; j < to; j++ {
		if run[j].End <= opener.End && run[j].Start >= opener.Start {
			end = j + 1
			continue
		}
		break
	}
	return end
}

func (r *htmlRenderer) writeLink(run []markdown.Inline, i, to int) {
	opener := run[i]
	end := r.childClose(run, i, to, opener)
	href, ok := r.resolveLink(opener.Dest)
	if !ok || href == "" {
		r.b.WriteString("<span class=\"docgen-badref\">")
		r.writeInlineSpan(run, i+1, end)
		r.b.WriteString("</span>")
		return
	}
	r.b.WriteString("<a href=\"" + html.EscapeString(href) + "\"")
	if opener.Title != "" {
		r.b.WriteString(" title=\"" + html.EscapeString(opener.Title) + "\"")
	}
	r.b.WriteString(">")
	r.writeInlineSpan(run, i+1, end)
	r.b.WriteString("</a>")
}

func (r *htmlRenderer) resolveLink(dest string) (string, bool) {
	if r.opts.ResolveLink != nil {
		return r.opts.ResolveLink(r.opts.SourceRel, dest)
	}
	return defaultResolveLink(dest)
}

// defaultResolveLink is the hook-free fallback: gorequest links map to the
// card anchor of the same page, external http(s)/mailto stay, relative .md
// links become .html, and everything else renders plainly.
func defaultResolveLink(dest string) (string, bool) {
	if id, ok := ParseRefLink(dest); ok {
		return "#" + cardAnchor(id), true
	}
	if IsValidRefShape(dest) {
		return "", false
	}
	switch {
	case strings.HasPrefix(dest, "http://"), strings.HasPrefix(dest, "https://"), strings.HasPrefix(dest, "mailto:"):
		return dest, true
	case strings.HasPrefix(dest, "#"):
		return dest, true
	}
	pathPart, frag, _ := strings.Cut(dest, "#")
	if strings.HasSuffix(strings.ToLower(pathPart), ".md") {
		return pathPart[:len(pathPart)-3] + ".html" + fragmentURI(frag), true
	}
	return "", false
}

func (r *htmlRenderer) writeImage(run []markdown.Inline, i, to int) {
	opener := run[i]
	end := r.childClose(run, i, to, opener)
	alt := markdown.PlainText(run[i+1 : end])
	url, ok, note := "", false, ""
	if r.opts.ResolveImage != nil {
		url, ok, note = r.opts.ResolveImage(r.opts.SourceRel, opener.Dest)
	} else {
		note = "no image exporter; the image is not embedded"
	}
	if !ok {
		if note != "" {
			r.b.WriteString("<span class=\"docgen-remote-img\">" + html.EscapeString(note) + "</span> ")
		}
		r.b.WriteString("<em>[" + html.EscapeString(alt) + "]</em>")
		return
	}
	r.b.WriteString("<img src=\"" + html.EscapeString(url) + "\" alt=\"" + html.EscapeString(alt) + "\">")
}
