// RenderOptions drives the static HTML renderer.
type RenderOptions struct {
	// SourceRel is the project-relative path of the rendered document; the
	// resolve hooks use it to resolve relative destinations.
	SourceRel string
	// ResolveLink maps a Markdown link destination to an href. ok=false
	// renders the label as plain marked text. Relative destinations must be
	// confined to the export set; dangerous schemes must not resolve.
	ResolveLink func(sourceRel, dest string) (href string, ok bool)
	// ResolveImage maps an image destination to a local export-relative
	// URL. ok=false renders the alt text plus a visible note. Remote images
	// must resolve ok=false: an offline export never references or fetches
	// them.
	ResolveImage func(sourceRel, dest string) (url string, ok bool, note string)
	// Cards locate derived card headings (line numbers in the expanded
	// text) so they become anchor targets of gorequest links.
	Cards []CardSite
	// MermaidNote is the visible warning attached to Mermaid sources that
	// are outside the supported offline subset. Source is always kept.
	MermaidNote string
	// Diagram configures the offline flowchart/sequence renderer. The zero
	// value renders the supported subset; Disable restores the source-only
	// fallback for callers that need byte-stable old output.
	Diagram DiagramOptions
}

// DiagramOptions control the offline Mermaid renderer of the HTML export.
type DiagramOptions struct {
	// Disable keeps every Mermaid fence as source with the fallback note.
	Disable bool
	// Theme is the SVG palette; the zero value uses the light palette.
	Theme diagram.SVGTheme
	// FontSize is the scene base text size in DIP; zero uses 14.
	FontSize float32
}

// DefaultMermaidNote is the warning used when opts.MermaidNote is empty.
const DefaultMermaidNote = "This Mermaid diagram is outside the supported offline subset (flowchart, sequenceDiagram); the source is kept as-is."

// RenderHTML renders one Markdown text (already docgen-expanded) into a
// static body fragment. The output contains no scripts, no remote resources,
// no event handlers and no external CSS: the export writer wraps it with the
// shared inline stylesheet. All text and attribute content is HTML-escaped.
func RenderHTML(src string, opts RenderOptions) string {
	if opts.MermaidNote == "" {
		opts.MermaidNote = DefaultMermaidNote
	}
	d := markdown.Parse(src)
	r := &htmlRenderer{
		src:       src,
		opts:      opts,
		cardLines: map[int]string{},
		doc:       d,
	}
	for _, site := range opts.Cards {
		r.cardLines[site.HeadingLine] = cardAnchor(site.RequestID)
	}
	roots := buildBlockTree(src, d.Blocks())
	r.writeChildren(roots)
	return r.b.String()
}

// RenderHTMLDocument wraps a body fragment into a standalone page with the
// shared inline stylesheet and an honest generation footer.
func RenderHTMLDocument(title, bodyHTML string) string {
	var b strings.Builder
	b.WriteString("<!doctype html>\n<html lang=\"zh-CN\">\n<head>\n<meta charset=\"utf-8\">\n")
	b.WriteString("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
	b.WriteString("<title>" + html.EscapeString(title) + "</title>\n")
	b.WriteString(exportStylesheet)
	b.WriteString("\n</head>\n<body>\n<main>\n")
	b.WriteString(bodyHTML)
	b.WriteString("\n</main>\n<footer class=\"docgen-footer\">")
	b.WriteString(html.EscapeString("Generated by GoRequest docgen - offline static export; no scripts, no remote resources."))
	b.WriteString("</footer>\n</body>\n</html>\n")
	return b.String()
}

